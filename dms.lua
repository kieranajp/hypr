-- Dux Modular Shell (dux-shell) owns the bar, notifications, launcher, lock,
-- polkit agent and wallpaper. It's wired in by hand rather than via
-- `dms setup`, which would rewrite hyprland.lua and binds.
--
-- We deliberately don't require dms.binds/colors/layout/input/outputs: those
-- would fight keybinds.lua, colours.lua, appearance.lua and monitors.lua. That
-- also means DMS Settings pages for borders, gaps, input and displays do
-- nothing here. Only its window rules are loaded.
--
-- hypridle stays (startup.lua) since it only dims the OLED.

pcall(require, "dms.windowrules") -- generated by `dms setup windowrules`

local dms = function(c) return "dms ipc call " .. c end

return {
    start = { "dms run" },

    binds = {
        ["SUPER + D"]             = dms("spotlight toggle"),
        ["SUPER + E"]             = "dfiles show",
        -- Dash tabs: overview, media, wallpaper, weather, wellbeing
        ["SUPER + A"]             = dms("dash toggle overview"),
        ["SUPER + M"]             = dms("dash toggle media"),
        ["SUPER + Y"]             = dms("dash toggle wallpaper"),
        ["SUPER + W"]             = dms("dash toggle weather"),
        ["SUPER + C"]             = dms("control-center toggle"),
        ["SUPER + slash"]         = dms("hypr toggleBinds"),
        ["SUPER + N"]             = dms("notepad toggle"),
        ["SUPER + CTRL + N"]      = dms("notifications toggle"),
        ["SUPER + O"]             = dms("hypr toggleOverview"),
        ["SUPER + V"]             = dms("clipboard toggle"),
        ["SUPER + ALT + L"]       = dms("lock lock"),
        ["SUPER + comma"]         = dms("settings focusOrToggle"),
        ["SUPER + SHIFT + E"]     = dms("powermenu toggle"),
        ["CTRL + SHIFT + Escape"] = dms("processlist focusOrToggle"),
    },
}
