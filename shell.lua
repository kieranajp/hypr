-- Which shell owns the bar/notifications/launcher: "hyprpanel" or "dms".
-- The choice lives in ~/.config/hypr/shell (one word, gitignored) so
-- scripts/shell-switch.sh can flip it without touching tracked files.
--
-- Anything that differs between shells goes here: what to start, and the
-- handful of binds that point at shell features. Core window-management binds
-- stay in keybinds.lua and never change.
--
-- If you add a long-running process to `start`, add it to the matching
-- stop_* function in scripts/shell-switch.sh too.

local p = require("vars")

local function read_choice()
    local f = io.open(os.getenv("HOME") .. "/.config/hypr/shell", "r")
    if not f then return "dms" end
    local s = (f:read("l") or ""):match("^%s*(%S+)")
    f:close()
    return s or "dms"
end

local dms = function(c) return "dms ipc call " .. c end

local shells = {
    hyprpanel = {
        start = {
            "~/.config/hypr/scripts/hyprpanel.sh",
            "~/.config/hypr/wallpaper.sh ~/Pictures/Walls/veil-nebula-purple.jpg",
            "/usr/lib/polkit-gnome/polkit-gnome-authentication-agent-1",
        },
        binds = {
            ["SUPER + D"] = p.menu,
            ["SUPER + E"] = p.file_manager,
        },
    },

    -- DMS brings its own polkit agent, wallpaper and lock. hypridle stays
    -- (startup.lua) since it only dims the OLED, which DMS knows nothing of.
    -- We deliberately don't require dms.binds/colors/layout/input: those
    -- would fight keybinds.lua, colours.lua and appearance.lua.
    dms = {
        start = { "dms run" },
        binds = {
            ["SUPER + D"]            = dms("spotlight toggle"),
            ["SUPER + E"]            = "dfiles show",
            -- Dash tabs: overview, media, wallpaper, weather, wellbeing
            ["SUPER + A"]            = dms("dash toggle overview"),
            ["SUPER + M"]            = dms("dash toggle media"),
            ["SUPER + Y"]            = dms("dash toggle wallpaper"),
            ["SUPER + W"]            = dms("dash toggle weather"),
            ["SUPER + C"]            = dms("control-center toggle"),
            ["SUPER + slash"]        = dms("hypr toggleBinds"),
            ["SUPER + N"]            = dms("notepad toggle"),
            ["SUPER + CTRL + N"]     = dms("notifications toggle"),
            ["SUPER + O"]            = dms("hypr toggleOverview"),
            ["SUPER + V"]            = dms("clipboard toggle"),
            ["SUPER + ALT + L"]      = dms("lock lock"),
            ["SUPER + comma"]        = dms("settings focusOrToggle"),
            ["SUPER + SHIFT + E"]    = dms("powermenu toggle"),
            ["CTRL + SHIFT + Escape"] = dms("processlist focusOrToggle"),
        },
        -- Rules DMS needs for its own floating windows (settings etc).
        -- Generated by `dms setup windowrules`; skipped if absent.
        requires = { "dms.windowrules" },
    },
}

local name = read_choice()
local shell = shells[name]
if not shell then
    hl.exec_cmd("notify-send -u critical Hyprland 'Unknown shell \"" .. name .. "\", falling back to hyprpanel'")
    name, shell = "hyprpanel", shells.hyprpanel
end

for _, mod in ipairs(shell.requires or {}) do
    pcall(require, mod)
end

return {
    name  = name,
    start = shell.start,
    binds = shell.binds,
}
